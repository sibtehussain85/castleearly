  // A real sacrifice: a piece moves where it can be taken and the opponent comes out ahead in material.
  function isSacrifice(fen, uci) {
    var c = new Chess(fen), us = c.turn, them = us === "w" ? "b" : "w";
    var r = c.move(uci);
    if (!r || r.promotion) return false;
    var t = r.piece.toLowerCase(), v = VAL[t], got = r.captured ? VAL[r.captured.toLowerCase()] : 0;
    if (t === "p" || t === "k" || v - got < 2) return false;
    var to = Chess.sqIdx(uci.slice(2, 4));
    if (!c.attacked(to, them)) return false;
    var takers = c.legalMoves().filter(function (m) { return m.to === to; });
    if (!takers.length) return false;
    var cheapest = Math.min.apply(null, takers.map(function (m) { return VAL[m.piece.toLowerCase()]; }));
    return !c.attacked(to, us) || cheapest < v;
  }

  /* ---------- Background analysis pool ---------- */
  function Runner(jobs, ms, onResult, onDone) {
    var self = this;
    this.jobs = jobs; this.ms = ms; this.next = 0; this.left = jobs.length;
    this.onResult = onResult; this.onDone = onDone; this.workers = []; this.stopped = false;
    var n = Math.max(1, Math.min(4, (navigator.hardwareConcurrency || 2) - 1));
    if (window.Worker && P.engineUrl) {
      for (var i = 0; i < n; i++) {
        try {
          var w = new Worker(P.engineUrl);
          w.onmessage = function (e) { self.got(this, e.data); };
          w.onerror = function () { self.fail(this); };
          this.workers.push(w);
        } catch (e) { break; }
      }
    }
    if (!this.workers.length) { this.mainThread(); return; }
    this.workers.forEach(function (w) { self.feed(w); });
  }
  Runner.prototype.feed = function (w) {
    if (this.stopped || this.next >= this.jobs.length) { w.job = null; return; }
    var i = this.next++, j = this.jobs[i];
    w.job = i;
    w.postMessage({ id: i, fen: j.fen, analyze: { ms: this.ms, played: j.played } });
  };
  Runner.prototype.got = function (w, d) {
    if (this.stopped) return;
    if (d.error || !d.analysis) { this.fail(w); return; }
    this.result(d.id, d.analysis);
    this.feed(w);
  };
  Runner.prototype.result = function (i, a) {
    this.onResult(i, a);
    if (--this.left === 0) { this.stop(); this.onDone(); }
  };
  Runner.prototype.fail = function (w) { // a worker broke: finish its job (and the rest) on the main thread
    var i = w.job;
    try { w.terminate(); } catch (e) {}
    this.workers = this.workers.filter(function (x) { return x !== w; });
    if (i != null) this.jobs[i].retry = true;
    if (!this.workers.length) this.mainThread();
  };
  Runner.prototype.mainThread = function () {
    var self = this;
    var todo = [];
    this.jobs.forEach(function (j, i) { if (i >= self.next || j.retry) todo.push(i); });
    this.next = this.jobs.length;
    (function step() {
      if (self.stopped || !todo.length) return;
      var i = todo.shift(), j = self.jobs[i];
      self.result(i, new Chess(j.fen).analyze(Math.min(self.ms, 250), j.played));
      setTimeout(step, 15);
    })();
  };
  Runner.prototype.stop = function () {
    this.stopped = true;
    this.workers.forEach(function (w) { try { w.terminate(); } catch (e) {} });
    this.workers = [];
  };

  /* ---------- Stockfish 19 lite pool ---------- */
  var SF_GO = "depth 15 movetime 1500";
  function SfRunner(fens, onResult, onDone, onFail) {
    var self = this;
    this.fens = fens; this.todo = []; this.left = 0; this.stopped = false;
    this.onResult = onResult; this.onDone = onDone; this.onFail = onFail; this.lastErr = "";
    fens.forEach(function (f, i) {
      var st = new Chess(f).status();
      if (st.over) setTimeout(function () { if (!self.stopped) self.result(i, { best: null, score: st.reason === "checkmate" ? -MATE : 0, depth: 0 }); }, 0);
      else self.todo.push(i);
      self.left++;
    });
    var n = Math.max(1, Math.min(3, (navigator.hardwareConcurrency || 2) - 1));
    this.engines = [];
    for (var k = 0; k < n; k++) this.engines.push(new P.UciEngine());
    this.engines.forEach(function (e) { self.feed(e); });
  }
  SfRunner.prototype.feed = function (e) {
    var self = this;
    if (this.stopped || !this.todo.length) return;
    var i = this.todo.shift();
    e.search(this.fens[i], SF_GO, function (err, r) {
      if (self.stopped) return;
      if (err || !r || (!r.best && !new Chess(self.fens[i]).status().over)) {
        self.lastErr = err || "it returned no move";
        self.todo.unshift(i);
        self.engines = self.engines.filter(function (x) { return x !== e; });
        e.stop();
        if (!self.engines.length) { self.stop(); self.onFail(self.lastErr); }
        return;
      }
      self.result(i, r);
      self.feed(e);
    });
  };
  SfRunner.prototype.result = function (i, r) {
    this.onResult(i, r);
    if (--this.left === 0) { this.stop(); this.onDone(); }
  };
  SfRunner.prototype.stop = function () {
    this.stopped = true;
    this.engines.forEach(function (e) { e.stop(); });
  };
  // Stockfish scores each position once; the played move's score is the (negated) score of the next position.
  function finishSfResults(rv) {
    for (var i = 0; i <= rv.moves.length; i++) {
      var a = rv.res[i];
      a.n = new Chess(rv.fens[i]).legalMoves().length;
      if (i === rv.moves.length) { a.played = null; a.playedScore = null; continue; }
      a.played = rv.moves[i];
      var ps = -rv.res[i + 1].score;
      a.playedScore = a.best === rv.moves[i] || ps > a.score ? a.score : ps;
    }
  }

  /* ---------- Turning engine numbers into a review ---------- */
  function classify(rv) {
    var out = [], stillBook = true;
    for (var i = 0; i < rv.moves.length; i++) {
      var a = rv.res[i], fen = rv.fens[i], uci = rv.moves[i];
      var mover = fen.split(" ")[1];
      var best = a.score, played = a.playedScore == null ? a.score : a.playedScore;
      var wpBest = winPct(best), wpPlayed = winPct(played);
      var drop = Math.max(0, wpBest - wpPlayed);
      var isBest = uci === a.best || played >= best - 5;
      var cls = null;
      if (a.n === 1) cls = "forced";
      else if (stillBook && inBook(fen, uci)) cls = "book";
      else if (isBest) {
        cls = "best";
        if (isSacrifice(fen, uci) && (isMate(played) ? played > 0 && mateIn(played) >= 2 : wpPlayed >= 45 && wpBest < 97)) cls = "brilliant";
      }
      else if (isMate(best) && best > 0 && !(isMate(played) && played > 0)) cls = mateIn(best) <= 1 ? "mistake" : mateIn(best) <= 3 && drop < 10 ? "inaccuracy" : null;
      if (!cls) cls = drop < 2 ? "excellent" : drop < 5 ? "good" : drop < 10 ? "inaccuracy" : drop < 20 ? "mistake" : "blunder";
      if (cls !== "book" && cls !== "forced") stillBook = false;
      if (cls === "excellent" && drop < 0.5) cls = "best";
      var acc = cls === "book" || cls === "forced" ? 100 : moveAccuracy(drop);
      if (cls === "mistake" && isMate(best)) acc = Math.min(acc, 60);
      out.push({ cls: cls, color: mover, drop: drop, acc: acc, best: a.best, bestScore: best, playedScore: played });
    }
    return out;
  }

  // Score of every position from White's point of view (for the bar and the graph)
  function whiteEvals(rv) {
    var ev = [];
    for (var k = 0; k <= rv.moves.length; k++) {
      var fen = rv.fens[k], turn = fen.split(" ")[1], s;
      var st = new Chess(fen).status();
      if (st.over) s = st.result === "1-0" ? MATE : st.result === "0-1" ? -MATE : 0;
      else { var a = rv.res[k]; s = turn === "w" ? a.score : -a.score; }
      ev.push(s);
    }
    return ev;
  }

  function summary(rv) {
    var s = { w: { acc: 0, n: 0, counts: {} }, b: { acc: 0, n: 0, counts: {} } };
    rv.cls.forEach(function (c) {
      var side = s[c.color];
      side.counts[c.cls] = (side.counts[c.cls] || 0) + 1;
      if (c.cls !== "forced") { side.acc += c.acc; side.n++; }
    });
    ["w", "b"].forEach(function (k) { s[k].acc = s[k].n ? s[k].acc / s[k].n : null; });
    // Opening name: the deepest named book position of the game
    var op = null;
    for (var i = 1; i <= rv.moves.length && i <= 30; i++) { var o = openingAfter(rv.fens[i]); if (o) op = o; }
    if (!op && rv.moves.length && rv.fens[0] === Chess.START_FEN && FIRST[rv.moves[0]]) {
      op = { slug: rv.moves[0] === "c2c4" ? "english-opening" : null, name: FIRST[rv.moves[0]] };
    }
    s.opening = op;
    return s;
  }

